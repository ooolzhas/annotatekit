// AppInfo.framework (React Native / Expo detection) on disk and in the prompt: old bundles without
// the field still decode, and only RN/Expo sessions get the line pointing at the JS/TS source.

import Foundation
import Testing
@testable import AnnotateCore

struct FrameworkPromptTests {
    @Test func appInfoWithoutFrameworkDecodes() throws {
        // A bundle written before `framework` existed.
        let json = #"{"bundleID":"com.example.app","name":"Example","version":"1.0","build":"7"}"#
        let app = try AnnotationSession.decoder.decode(AppInfo.self, from: Data(json.utf8))
        #expect(app.framework == nil)
        #expect(app == AppInfo(bundleID: "com.example.app", name: "Example", version: "1.0", build: "7"))
    }

    @Test(arguments: ["react-native", "expo"])
    func appInfoRoundTripsFramework(_ framework: String) throws {
        let app = AppInfo(bundleID: "com.example.app", installFile: "/Users/me/app/ios/AppDelegate.mm", framework: framework)
        let data = try AnnotationSession.encoder.encode(app)
        #expect(String(decoding: data, as: UTF8.self).contains(#""framework" : "\#(framework)""#))
        #expect(try AnnotationSession.decoder.decode(AppInfo.self, from: data) == app)
    }

    @Test func nativeAppOmitsFrameworkKey() throws {
        let data = try AnnotationSession.encoder.encode(AppInfo(bundleID: "com.example.app"))
        #expect(!String(decoding: data, as: UTF8.self).contains("framework"))
    }

    @Test(arguments: [
        ("react-native", "UI: React Native. Edit the JS/TS components; change native code under ios/ only for native modules."),
        ("expo", "UI: Expo (React Native). Edit the JS/TS components; ios/ is regenerated by `expo prebuild`, so never edit it."),
    ])
    func promptHasFrameworkLineAfterDevice(_ framework: String, _ expected: String) throws {
        var session = Fixtures.session(annotations: [Fixtures.element])
        session.app.framework = framework
        let lines = PromptRenderer.render(session, sessionPath: "/tmp/s").components(separatedBy: "\n")
        let device = try #require(lines.firstIndex { $0.hasPrefix("Device: ") })
        #expect(lines[device + 1] == expected)
        #expect(lines.filter { $0.hasPrefix("UI: ") }.count == 1)
    }

    @Test func nativePromptIsUnchanged() {
        let native = Fixtures.session(annotations: [Fixtures.element])
        var unknown = native
        unknown.app.framework = "flutter" // not a value the app writes; ignored rather than guessed at
        let prompt = PromptRenderer.render(native, sessionPath: "/tmp/s")
        #expect(!prompt.contains("UI: "))
        #expect(PromptRenderer.render(unknown, sessionPath: "/tmp/s") == prompt)
    }
}
